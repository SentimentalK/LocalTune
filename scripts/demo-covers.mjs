// Generate the demo cover variants from design/demo-covers/*.jpg.
//
// Each source becomes two content-addressed WebPs in src/demo/:
//   <slug>.<hash>.webp       640 px on the long edge, for the stage
//   <slug>.<hash>-96.webp    96×96 crop, for list rows
// `<hash>` is the first 8 hex digits of the output's own SHA-256, so a changed
// image always gets a new URL and nginx can serve /demo/ as immutable for a
// year. `src/core/demoCovers.generated.js` is rewritten to match.
//
// Requires ffmpeg with libwebp (`npm run covers`).

import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdir, readFile, rename, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const run = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, 'design', 'demo-covers');
const outputDir = path.join(root, 'src', 'demo');
const manifestPath = path.join(root, 'src', 'core', 'demoCovers.generated.js');

const STAGE_EDGE = 640;
const THUMB_EDGE = 96;
// Task budget: 640 px ≤ 90 KB, 96 px ≤ 12 KB.
const LIMITS = { stage: 90 * 1024, thumb: 12 * 1024 };

/** ffmpeg libwebp: `-q:v` is the quality knob that actually takes effect. */
async function encode(source, temp, filter, quality) {
  await run('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-i',
    source,
    '-vf',
    filter,
    '-c:v',
    'libwebp',
    '-q:v',
    String(quality),
    '-map_metadata',
    '-1',
    temp,
  ]);
}

/** Read a freshly encoded temp file, hash it, and move it to its final URL. */
async function contentAddress(slug, suffix, temp) {
  const bytes = await readFile(temp);
  const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 8);
  const name = `${slug}.${hash}${suffix}.webp`;
  await rename(temp, path.join(outputDir, name));
  return { name, bytes: bytes.length };
}

const slugs = (await readdir(sourceDir))
  .filter((name) => name.endsWith('.jpg'))
  .map((name) => name.slice(0, -'.jpg'.length))
  .sort();

if (slugs.length === 0) {
  throw new Error(`no .jpg covers in ${sourceDir}`);
}

const covers = {};
const produced = new Set();
let stageTotal = 0;
let thumbTotal = 0;

for (const slug of slugs) {
  const source = path.join(sourceDir, `${slug}.jpg`);
  const stageTemp = path.join(outputDir, `.${slug}-stage.tmp.webp`);
  const thumbTemp = path.join(outputDir, `.${slug}-thumb.tmp.webp`);

  await encode(
    source,
    stageTemp,
    `scale=${STAGE_EDGE}:${STAGE_EDGE}:force_original_aspect_ratio=decrease`,
    78,
  );
  await encode(
    source,
    thumbTemp,
    `scale=${THUMB_EDGE}:${THUMB_EDGE}:force_original_aspect_ratio=increase,crop=${THUMB_EDGE}:${THUMB_EDGE}`,
    80,
  );

  const stage = await contentAddress(slug, '', stageTemp);
  const thumb = await contentAddress(slug, '-96', thumbTemp);

  if (stage.bytes > LIMITS.stage) {
    throw new Error(`${stage.name} is ${stage.bytes} B, over the ${LIMITS.stage} B budget`);
  }
  if (thumb.bytes > LIMITS.thumb) {
    throw new Error(`${thumb.name} is ${thumb.bytes} B, over the ${LIMITS.thumb} B budget`);
  }

  covers[slug] = { src: `./demo/${stage.name}`, thumb: `./demo/${thumb.name}` };
  produced.add(stage.name).add(thumb.name);
  stageTotal += stage.bytes;
  thumbTotal += thumb.bytes;

  console.log(
    `${slug.padEnd(20)} stage ${String(stage.bytes).padStart(6)} B  thumb ${String(thumb.bytes).padStart(5)} B`,
  );
}

// Drop variants of covers that no longer exist (renamed or removed sources).
for (const name of await readdir(outputDir)) {
  if (name.endsWith('.webp') && !produced.has(name)) {
    await rm(path.join(outputDir, name));
    console.log(`removed stale ${name}`);
  }
}

const manifest = `// Generated by scripts/demo-covers.mjs — do not edit.
// Run \`npm run covers\` to regenerate from design/demo-covers/*.jpg.

export const DEMO_COVERS = ${JSON.stringify(covers, null, 2)};
`;
await writeFile(manifestPath, manifest);

console.log(
  `\ntotal: stage ${stageTotal} B + thumb ${thumbTotal} B = ${stageTotal + thumbTotal} B`,
);
